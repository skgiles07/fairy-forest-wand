"""Clue-card generator. Stdlib only.

    python3 hub/cards.py hub/adventures/campaign.json [--out cards/chapters] [--check]
    python3 hub/cards.py hub/adventures/02-crystal-caves.json

Writes one Markdown file per chapter (opening, one card per step, ending)
from the same JSON the TV reads, so cards and screen never disagree. Each
card names the PHYSICAL object (STATION_OBJECTS below) and the chapter's
spot name for that station.

--check: after writing, re-parse the Markdown and require it to contain
exactly the (chapter, step, station, spot) set derived from the JSON.
Missing cards, omitted stations, or a station paired with the wrong spot
exit 1.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent

# Three fixed physical landmarks; story ingredients change, object identity never does.
STATION_OBJECTS = {
    1: "the Moon Crystal",
    2: "the Elder Tree",
    3: "the Treasure Chest",
}

CARD_RE = re.compile(r"^- \*\*Station (\d)\*\* \((.+?)\): (.+?)\s*$")
HEAD_RE = re.compile(r"^## Card (\d+)\b")


def stations_of(step):
    mode = step.get("mode", "ordered")
    if mode == "dialogue":
        return []
    if mode == "collect":
        return list(step["stations"])
    if mode == "puzzle" or (mode == "boss" and step.get("pattern")):
        return list(step["pattern"])
    return [step["station"]]


def label(step, n):
    spots = step.get("spots") or {}
    return spots.get(str(n)) or spots.get(n) or step.get("spot")


def expected_tuples(ci, adv):
    out = set()
    for si, step in enumerate(adv["steps"]):
        for n in dict.fromkeys(stations_of(step)):   # unique, order kept
            out.add((ci, si, n, label(step, n)))
    return out


def card_md(si, step):
    mode = step.get("mode", "ordered")
    lines = [f"## Card {si + 1}: {step.get('title', 'Quest')}"]
    if mode == "dialogue":
        lines.append("**Return to the TV.** Read or listen, then press Continue / Enter.")
    if mode == "collect":
        lines.append(f"**Find all {len(step['stations'])}, any order.** One wave at each.")
    elif mode == "puzzle":
        names = " → ".join(label(step, n) for n in step["pattern"])
        lines.append(f"**Wave in this order:** {names}. A wrong wave starts the pattern over.")
    elif mode == "charge":
        lines.append(f"**Wave {step['hits']} times** at the same spot to charge the spell.")
    elif mode == "boss":
        names = " → ".join(label(step, n) for n in (step.get("pattern") or [step["station"]]))
        lines.append(f"**Untangle {step['hp']} knots:** {names}. Follow the TV's next landmark. There is no travel countdown.")
    lines.append("")
    lines.append(f"> {step['clue']}")
    if step.get("reward"):
        lines.append(f"\nSpell learned: **{step['reward']['spell']}**.")
    if step.get("spell"):
        lines.append(f"\nUse **{step['spell']}**.")
    lines.append("")
    for n in dict.fromkeys(stations_of(step)):
        lines.append(f"- **Station {n}** ({STATION_OBJECTS[n]}): {label(step, n)}")
        item = step.get("items_by_station", {}).get(str(n))
        if item:
            lines.append(f"  Find: {item}")
    lines.append("")
    if stations_of(step):
        lines.append("Landmark rooms: use the same three places throughout the whole story.")
    lines.append("")
    return "\n".join(lines)


def chapter_md(ci, adv, fname):
    mentor = adv.get("mentor") or adv.get("villain")
    head = [f"# Chapter {ci + 1}: {adv['title']}", ""]
    head.append(f"_Generated by `hub/cards.py` from `{fname}`. Do not edit; change the JSON._  ")
    head.append(f"_Scene: {adv.get('scene', 'forest')}" + (f" · {mentor}" if mentor else "") + "._")
    head += ["", "Print, cut along the lines, hand Liza card 1. Each card points to the",
             "next landmark. Dialogue cards send her back to the TV. Use only sensors 1–3.", ""]
    head += ["## Opening (read aloud)", "", adv["opening"], ""]
    body = [card_md(si, s) for si, s in enumerate(adv["steps"])]
    tail = ["## Ending (read after restoring this land)", "", adv["ending"], ""]
    return "\n".join(head + body + tail)


def parse_md(ci, text):
    found, step = set(), None
    for line in text.splitlines():
        h = HEAD_RE.match(line)
        if h:
            step = int(h.group(1)) - 1
            continue
        m = CARD_RE.match(line)
        if m and step is not None:
            n = int(m.group(1))
            if STATION_OBJECTS.get(n) != m.group(2):
                raise SystemExit(f"check FAIL: chapter {ci + 1} card {step + 1}: station {n} named {m.group(2)!r}, "
                                 f"expected {STATION_OBJECTS.get(n)!r}")
            found.add((ci, step, n, m.group(3)))
    return found


def load_chapters(path):
    path = Path(path)
    cfg = json.loads(path.read_text())
    if "chapters" in cfg:
        return [(path.parent / f, json.loads((path.parent / f).read_text())) for f in cfg["chapters"]]
    return [(path, cfg)]


def out_name(ci, src):
    stem = src.stem
    if re.match(r"^\d{2}-", stem):
        return stem + ".md"
    slug = re.sub(r"[^a-z0-9]+", "-", src.stem.lower()).strip("-")
    return f"{ci + 1:02d}-{slug}.md"


def main(argv):
    args = list(argv)
    check = "--check" in args
    if check:
        args.remove("--check")
    out = HERE.parent / "cards" / "chapters"
    if "--out" in args:
        i = args.index("--out")
        out = Path(args[i + 1])
        del args[i:i + 2]
    if not args:
        print(__doc__)
        return 2
    chapters = load_chapters(args[0])
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for ci, (src, adv) in enumerate(chapters):
        target = out / out_name(ci, src)
        target.write_text(chapter_md(ci, adv, src.name))
        written.append(target)
        print(f"wrote {target}")
    if not check:
        return 0
    bad = 0
    for ci, ((src, adv), target) in enumerate(zip(chapters, written)):
        want = expected_tuples(ci, adv)
        got = parse_md(ci, target.read_text())
        if want != got:
            bad += 1
            for t in sorted(want - got):
                print(f"check FAIL: missing card line {t} in {target}")
            for t in sorted(got - want):
                print(f"check FAIL: unexpected card line {t} in {target}")
    if bad:
        return 1
    print(f"check ok: {len(written)} chapter files, {sum(len(expected_tuples(i, a)) for i, (_, a) in enumerate(chapters))} station cards")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
